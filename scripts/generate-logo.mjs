// Generates src/components/brand/logo-paths.ts: the canonical Presence Hospitality logo geometry.
//   - The mark is the official vector from the Canva pitch deck ("Presence Hospitality Pitch V1.0.pdf",
//     page 1 content stream), centred on its rotation point and normalised to a -50..50 box.
//   - The wordmark is "Presence Hospitality" in Hanken Grotesk 900, outlined to paths (kerning on,
//     tracking -0.045em), so the logo never depends on a font being installed (site, Canva, PDFs).
//   - Lockup proportions follow the deck: mark height = 1.5 × cap height, gap = 0.35em, mark centred
//     on the cap height.
// Usage: npm run brand:logo   (needs network for the font; then exports the files in public/brand)
import opentype from "opentype.js";
import { writeFileSync } from "node:fs";

const TEXT = "Presence Hospitality";
const SIZE = 100; // font size in lockup units
const TRACKING = -0.045; // em
const MARK_SCALE = 1.5; // × cap height
const GAP = 0.35; // em

// Deck vector (PDF user space, frame 0..2601.6), four closed shapes of four cubic segments each.
const DECK = [
  [[1509.45, 1653.09], [921.72, 1473.36, 601.41, 692.53, 1044.59, 333.31], [1317.38, 112.06, 1865.88, 439.86, 1488.4, 919], [2401.1, 375.42, 1166.05, -468.46, 690.67, 323.58], [343.75, 901.61, 744.73, 1689.18, 1509.45, 1653.09]],
  [[948.52, 1509.48], [1128.25, 921.76, 1909.08, 601.44, 2268.3, 1044.62], [2489.55, 1317.41, 2161.75, 1865.9, 1682.61, 1488.43], [2226.19, 2401.13, 3070.07, 1166.08, 2278.03, 690.7], [1700.01, 343.78, 912.43, 744.76, 948.52, 1509.48]],
  [[1092.13, 948.52], [1679.86, 1128.25, 2000.17, 1909.08, 1556.99, 2268.31], [1284.19, 2489.56, 735.7, 2161.76, 1113.17, 1682.62], [200.47, 2226.2, 1435.52, 3070.08, 1910.9, 2278.04], [2257.83, 1700.01, 1856.85, 912.43, 1092.13, 948.52]],
  [[1653.09, 1092.16], [1473.36, 1679.89, 692.53, 2000.2, 333.31, 1557.02], [112.05, 1284.23, 439.86, 735.73, 919, 1113.21], [375.42, 200.51, -468.46, 1435.56, 323.58, 1910.94], [901.61, 2257.85, 1689.18, 1856.88, 1653.09, 1092.16]],
];
const FRAME = 2601.6;
const n = (v) => +(((v - FRAME / 2) * 100) / FRAME).toFixed(2);
const markPath = DECK.map(([m, ...cs]) => `M${m.map(n).join(" ")}` + cs.map((c) => `C${c.map(n).join(" ")}`).join("") + "Z").join("");

async function loadFont() {
  // Without a browser user agent the Google Fonts CSS API serves TTF, which opentype.js reads.
  const res = await fetch("https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@900");
  if (!res.ok) throw new Error(`Google Fonts CSS request failed: ${res.status}`);
  const url = (await res.text()).match(/url\((https:[^)]+\.ttf)\)/)?.[1];
  if (!url) throw new Error("Hanken Grotesk 900 TTF not found in the Google Fonts response");
  const file = await fetch(url);
  if (!file.ok) throw new Error(`Font download failed: ${file.status}`);
  return opentype.parse(await file.arrayBuffer());
}

const font = await loadFont();
const em = font.unitsPerEm;
const capH = (font.tables.os2.sCapHeight / em) * SIZE;
const markSize = capH * MARK_SCALE;
const textX = markSize + GAP * SIZE;

// Glyph-by-glyph layout so kerning and tracking are explicit.
const glyphs = font.stringToGlyphs(TEXT);
const word = new opentype.Path();
let x = textX;
glyphs.forEach((g, i) => {
  word.extend(g.getPath(x, 0, SIZE));
  const last = i === glyphs.length - 1;
  const kern = last ? 0 : font.getKerningValue(g, glyphs[i + 1]);
  x += ((g.advanceWidth + kern) / em) * SIZE + (last ? 0 : TRACKING * SIZE);
});
const wb = word.getBoundingBox();
const markBox = { x1: 0, y1: -capH / 2 - markSize / 2, x2: markSize, y2: -capH / 2 + markSize / 2 };
const box = {
  x1: Math.min(markBox.x1, wb.x1),
  y1: Math.min(markBox.y1, wb.y1),
  x2: Math.max(markBox.x2, wb.x2),
  y2: Math.max(markBox.y2, wb.y2),
};
const r = (v) => +v.toFixed(2);
const lockup = {
  viewBox: [box.x1, box.y1, box.x2 - box.x1, box.y2 - box.y1].map(r).join(" "),
  width: r(box.x2 - box.x1),
  height: r(box.y2 - box.y1),
  // The mark's centre and size inside the lockup (the mark path is drawn in a -50..50 box).
  mark: { cx: r(markSize / 2), cy: r(-capH / 2), size: r(markSize) },
};

writeFileSync(
  "src/components/brand/logo-paths.ts",
  `// GENERATED by scripts/generate-logo.mjs — do not edit by hand.
// Mark: official vector from the Canva pitch deck. Wordmark: Hanken Grotesk 900, outlined.

/** The mark, drawn in a -50..50 box (viewBox "-50 -50 100 100"), filled with fill-rule evenodd. */
export const MARK_PATH = "${markPath}";

/** "Presence Hospitality" outlined, in lockup units (font size 100, baseline at y = 0). */
export const WORDMARK_PATH = "${word.toPathData(1)}";

/** Lockup geometry: the mark sits at (cx, cy) scaled to \`size\`; the wordmark path is already placed. */
export const LOCKUP = ${JSON.stringify(lockup)} as const;
`,
);
console.log("logo-paths.ts written", lockup);
