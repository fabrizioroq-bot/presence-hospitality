// Samples the "Presence" wordmark (Hanken Grotesk 800, tracking -0.04em) into dot positions for the
// intro loader. Renders in a real browser with the site's font, keeps opaque pixels on a jittered grid,
// and writes src/components/intro/wordmark-points.ts (x,y as 0..255 bytes, base64).
import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
const base = process.argv[2] ?? "http://localhost:3000";
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage();
await p.goto(base + "/en", { waitUntil: "networkidle" });
const res = await p.evaluate(async () => {
  await document.fonts.ready;
  const family = getComputedStyle(document.querySelector("h1")).fontFamily;
  const W = 1200, H = 300;
  const c = document.createElement("canvas");
  c.width = W; c.height = H;
  const g = c.getContext("2d");
  g.font = `800 250px ${family}`;
  g.letterSpacing = "-10px";
  g.textBaseline = "alphabetic";
  const m = g.measureText("Presence");
  const tw = m.width;
  g.fillText("Presence", (W - tw) / 2, 235);
  const d = g.getImageData(0, 0, W, H).data;
  const pts = [];
  const step = 6;
  let seed = 7;
  const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
  for (let y = 0; y < H; y += step) for (let x = 0; x < W; x += step) {
    const jx = x + (rnd() - 0.5) * step * 0.8, jy = y + (rnd() - 0.5) * step * 0.8;
    const i = (Math.round(jy) * W + Math.round(jx)) * 4 + 3;
    if (d[i] > 140) pts.push([jx, jy]);
  }
  // bounding box → normalise to bytes
  const xs = pts.map((q) => q[0]), ys = pts.map((q) => q[1]);
  const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
  const bytes = [];
  for (const [x, y] of pts) bytes.push(Math.round(((x - x0) / (x1 - x0)) * 255), Math.round(((y - y0) / (y1 - y0)) * 255));
  return { n: pts.length, aspect: (x1 - x0) / (y1 - y0), b64: btoa(String.fromCharCode(...bytes)), family };
});
await b.close();
writeFileSync(
  "src/components/intro/wordmark-points.ts",
  `// Generated by scripts/generate-wordmark-points.mjs — do not edit.\n// "Presence" in Hanken Grotesk 800: ${res.n} dots, x/y as bytes (0..255) across the wordmark box.\nexport const WORDMARK = { n: ${res.n}, aspect: ${res.aspect.toFixed(3)}, b64: "${res.b64}" };\n`,
);
console.log(res.n, "points, aspect", res.aspect.toFixed(2), res.family.slice(0, 40));
